func fixedTime() time.Time {
	return time.Date(2026, 5, 29, 18, 0, 0, 0, time.UTC)
}

func TestInit_SeedsTenDataFiles(t *testing.T) {
	tmp := t.TempDir()
	if err := Init(tmp, "", ""); err != nil {
		t.Fatalf("Init: %v", err)
	}
	wantFiles := []string{
		"run_state.js", "timeline.js", "milestones.js", "security.js",
		"reports.js", "metrics.js", "health.js", "diagnosis.js",
		"inbox.js", "notes.js",
	}
	for _, name := range wantFiles {
		path := filepath.Join(tmp, ".claude", "dashboard", "data", name)
		body, err := os.ReadFile(path)
		if err != nil {
			t.Errorf("missing seed file %s: %v", name, err)
			continue
		}
		if !strings.HasPrefix(string(body), "// Generated by Tekhton") {
			t.Errorf("seed %s missing JS header: %q", name, string(body)[:min(40, len(body))])
		}
	}
}

func TestInit_PreservesExistingFiles(t *testing.T) {
	tmp := t.TempDir()
	if err := Init(tmp, "", ""); err != nil {
		t.Fatalf("first Init: %v", err)
	}
	// Mutate one seed; re-init should NOT clobber it.
	runStatePath := filepath.Join(tmp, ".claude", "dashboard", "data", "run_state.js")
	if err := os.WriteFile(runStatePath, []byte("custom data"), 0o644); err != nil {
		t.Fatalf("mutate seed: %v", err)
	}
	if err := Init(tmp, "", ""); err != nil {
		t.Fatalf("second Init: %v", err)
	}
	body, err := os.ReadFile(runStatePath)
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	if string(body) != "custom data" {
		t.Fatalf("Init clobbered existing file; got %q", body)
	}
}

